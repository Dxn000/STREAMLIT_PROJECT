with tab1:
    st.markdown("### 🎛️ Real-Time Environmental Telemetry & Output Predictor")
    st.write("Tune the environmental sensors and operating parameters to forecast photovoltaic alternating current (AC) power delivery.")

    col1, col2 = st.columns([1, 1], gap="large")

    with col1:
        st.subheader("Environmental Sensors")

        preset = st.selectbox(
            "Select Weather Preset (Optional Quick Setup)",
            options=["Custom", "Peak Summer Afternoon (Clear Sky)", "Overcast / Diffuse Daylight", "Early Morning Dawn", "Nighttime (Standby)"]
        )

        # Default values according to presets
        if preset == "Peak Summer Afternoon (Clear Sky)":
            def_irr, def_amb, def_mod, def_hour, def_yield = 0.95, 34.0, 56.0, 13, 5200.0
        elif preset == "Overcast / Diffuse Daylight":
            def_irr, def_amb, def_mod, def_hour, def_yield = 0.22, 27.0, 31.0, 11, 1800.0
        elif preset == "Early Morning Dawn":
            def_irr, def_amb, def_mod, def_hour, def_yield = 0.05, 22.0, 23.5, 6, 120.0
        elif preset == "Nighttime (Standby)":
            def_irr, def_amb, def_mod, def_hour, def_yield = 0.00, 20.0, 19.5, 22, 7500.0
        else:
            def_irr, def_amb, def_mod, def_hour, def_yield = 0.72, 31.0, 47.5, 12, 3600.0

        irradiation = st.slider("Solar Irradiation (kW/m²)", min_value=0.0, max_value=1.25, value=def_irr, step=0.01, help="Incident solar flux density per square meter.")
        ambient_temp = st.slider("Ambient Temperature (°C)", min_value=15.0, max_value=45.0, value=def_amb, step=0.5, help="Surrounding outdoor air temperature.")
        module_temp = st.slider("PV Module Temperature (°C)", min_value=15.0, max_value=70.0, value=def_mod, step=0.5, help="Surface temperature of solar panels.")

        temp_diff = round(module_temp - ambient_temp, 2)
        st.caption(f"Calculated Thermal Differential (Module - Ambient): **{temp_diff:+.1f} °C**")

        c_a, c_b = st.columns(2)
        with c_a:
            hour = st.slider("Hour of Day (24h)", min_value=0, max_value=23, value=def_hour, step=1)
        with c_b:
            daily_yield = st.number_input("Accumulated Day Yield (kWh)", min_value=0.0, max_value=10000.0, value=def_yield, step=100.0)

    with col2:
        st.subheader("Grid Power Output Forecast")

        if best_model is not None:
            input_df = pd.DataFrame([{
                "ambient_temperature": ambient_temp,
                "module_temperature": module_temp,
                "temp_diff": temp_diff,
                "irradiation": irradiation,
                "daily_yield": daily_yield,
                "hour": hour
            }])

            pred_ac = max(0.0, float(best_model.predict(input_df)[0]))
            base_ac = max(0.0, float(baseline_model.predict(input_df)[0])) if baseline_model else None

            # Operational Status Classification
            if irradiation <= 0.001 or pred_ac < 1.0:
                status_badge = '<span class="badge-idle">STANDBY / NIGHT</span>'
                status_desc = "Zero irradiance. Inverter is in idle standby mode."
            elif irradiation < 0.25:
                status_badge = '<span class="badge-low">LOW YIELD</span>'
                status_desc = "Sub-optimal diffuse light (dawn, dusk, or heavy clouds)."
            elif irradiation < 0.65:
                status_badge = '<span class="badge-mod">MODERATE GENERATION</span>'
                status_desc = "Standard generation under partial sun."
            else:
                status_badge = '<span class="badge-peak">PEAK HARVEST</span>'
                status_desc = "High-irradiance regime delivering optimal electrical feed."

            # Result Display Card
            st.markdown(f"""
            <div class="metric-card">
                <div style="display: flex; justify-content: space-between; align-items: center;">
                    <span style="font-size: 0.95rem; font-weight: 600; color: #78350F;">FORECASTED AC GRID OUTPUT</span>
                    {status_badge}
                </div>
                <div style="font-size: 2.4rem; font-weight: 800; color: #B45309; margin: 0.3rem 0;">
                    {pred_ac:,.2f} <span style="font-size: 1.2rem; font-weight: 600;">kW</span>
                </div>
                <div style="font-size: 0.9rem; color: #92400E;">
                    {status_desc}
                </div>
            </div>
            """, unsafe_allow_html=True)

            # Model Variance
            if base_ac is not None:
                st.markdown("<br>", unsafe_allow_html=True)
                diff = pred_ac - base_ac
                m1, m2 = st.columns(2)
                with m1:
                    st.metric("Champion Model (GBDT)", f"{pred_ac:,.1f} kW")
                with m2:
                    st.metric("Linear Baseline", f"{base_ac:,.1f} kW", delta=f"{diff:+,.1f} kW vs Ensemble")

            # Clean Energy Metrics
            homes = round(pred_ac / 1.2, 1) if pred_ac > 0 else 0
            co2_kg = round(pred_ac * 0.82, 1) if pred_ac > 0 else 0
            st.markdown("---")
            st.markdown("#### 🌿 Clean Grid Impact Equivalents")
            e1, e2 = st.columns(2)
            with e1:
                st.metric("🏡 Homes Powered Simultaneously", f"~{homes:,.0f} homes", help="Based on average 1.2 kW continuous household load.")
            with e2:
                st.metric("💨 Avoided Carbon Emissions", f"~{co2_kg:,.1f} kg CO₂/hr", help="Based on 0.82 kg CO2/kWh thermal grid displacement.")

            # Gauge Chart
            gauge_fig = go.Figure(go.Indicator(
                mode="gauge+number",
                value=pred_ac,
                number={"suffix": " kW", "valueformat": ",.0f"},
                gauge={
                    "axis": {"range": [0, 1450], "ticksuffix": " kW"},
                    "bar": {"color": "#D97706"},
                    "steps": [
                        {"range": [0, 200], "color": "#FEF3C7"},
                        {"range": [200, 800], "color": "#FDE68A"},
                        {"range": [800, 1450], "color": "#DCFCE7"},
                    ],
                    "threshold": {
                        "line": {"color": "green", "width": 4},
                        "thickness": 0.75,
                        "value": 1100,
                    }
                },
                title={"text": "Plant Capacity Utilization"}
            ))
            gauge_fig.update_layout(height=250, margin=dict(l=20, r=20, t=40, b=10))
            st.plotly_chart(gauge_fig, use_container_width=True)

        else:
            st.error("Model artifacts not found. Run `python train.py` first.")

