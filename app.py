BASE_DIR = os.path.dirname(os.path.abspath(__file__))
DATA_PATH = os.path.join(BASE_DIR, "solar_power_dataset.csv")
MODEL_PATH = os.path.join(BASE_DIR, "models", "best_solar_model.pkl")
BASELINE_PATH = os.path.join(BASE_DIR, "models", "linear_baseline_model.pkl")
METRICS_PATH = os.path.join(BASE_DIR, "models", "metrics.json")


@st.cache_data
def load_dataset():
    if os.path.exists(DATA_PATH):
        return pd.read_csv(DATA_PATH)
    return None


@st.cache_resource
def load_models_and_metrics():
    best_model = joblib.load(MODEL_PATH) if os.path.exists(MODEL_PATH) else None
    baseline_model = joblib.load(BASELINE_PATH) if os.path.exists(BASELINE_PATH) else None
    metrics = None
    if os.path.exists(METRICS_PATH):
        with open(METRICS_PATH, "r", encoding="utf-8") as f:
            metrics = json.load(f)
    return best_model, baseline_model, metrics


